const content=document.getElementById("content");
const count=document.getElementById("count");
const search=document.getElementById("search");

function render(q=""){
  const query=q.trim().toLowerCase();
  let visible=0;
  content.innerHTML=parts.map((part,pi)=>{
    const groups=part.groups.map(group=>{
      const items=group.items.filter(item=>
        !query || (part.no+" "+part.title+" "+part.range+" "+group.title+" "+item[0]+" "+item[1]).toLowerCase().includes(query)
      );
      visible+=items.length;
      if(!items.length)return "";
      return `<div class="group-title">${group.title}</div>`+
        items.map(item=>`<article class="article"><h3>${item[0]}</h3><p>${item[1]}</p></article>`).join("");
    }).join("");
    if(!groups)return "";
    return `<section class="part" id="part-${pi+1}">
      <div class="part-head">
        <div class="part-no">${part.no}</div>
        <div class="part-title">${part.title}</div>
        <div class="range">${part.range}</div>
      </div>
      <div class="articles">${groups}</div>
    </section>`;
  }).join("");
  count.textContent=visible+" entries • "+parts.length+" listed Parts";
}
search.addEventListener("input",e=>render(e.target.value));
render();
</script>
